#!/usr/bin/env python3
"""Build src/i18n/ta.ts and src/i18n/hi.ts from scripts/i18n/*.tsv.

Each TSV line: English<TAB>Tamil<TAB>Hindi. The English text is the key the
UI passes to t(). Edit the TSV files (or have a native speaker review them),
then run:  python3 scripts/build-i18n.py
"""
import glob
import json
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = {}
for path in sorted(glob.glob(os.path.join(root, 'scripts', 'i18n', '*.tsv'))):
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) != 3:
                sys.exit(f'{os.path.basename(path)}:{n}: expected 3 columns, got {len(parts)}')
            en, ta, hi = parts
            rows[en] = (ta, hi)

for i, lang in enumerate(['ta', 'hi']):
    out = [f'// Generated by scripts/build-i18n.py from scripts/i18n/*.tsv — edit those, not this file.',
           f'const {lang}: Record<string, string> = {{']
    for en, tr in rows.items():
        out.append(f'  {json.dumps(en, ensure_ascii=False)}: {json.dumps(tr[i], ensure_ascii=False)},')
    out.append('};')
    out.append(f'export default {lang};')
    out.append('')
    with open(os.path.join(root, 'src', 'i18n', f'{lang}.ts'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
print(f'{len(rows)} strings written for ta and hi')
